"""Metrics and results logging shared by every model."""

import json
from pathlib import Path

from sklearn.metrics import precision_recall_fscore_support

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "results"


def micro_metrics(y_true, y_pred):
    """Micro-averaged precision, recall and F1 over all 217 label columns."""
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="micro", zero_division=0
    )
    return {"precision": float(precision), "recall": float(recall), "micro_f1": float(f1)}


def save_result(run_name, result):
    """Write one run to results/<run_name>.json and refresh results/summary.md."""
    RESULTS_DIR.mkdir(exist_ok=True)
    path = RESULTS_DIR / f"{run_name}.json"
    path.write_text(json.dumps(result, indent=2) + "\n")
    print(f"Wrote {path}")
    write_summary()


def write_summary():
    """Rebuild results/summary.md as one table of every run JSON in results/."""
    rows = []
    for path in sorted(RESULTS_DIR.glob("*.json")):
        r = json.loads(path.read_text())
        rows.append(
            f"| {path.stem} | {r['model']} | {r['threshold']} | {r['seed']} "
            f"| {r['precision']:.4f} | {r['recall']:.4f} | {r['micro_f1']:.4f} "
            f"| {r['runtime_seconds']:.0f} |"
        )
    lines = [
        "# Results summary",
        "",
        "Test-set metrics, micro-averaged over all 217 labels. Generated by",
        "`src/evaluate.py` from the JSON files in this folder; do not edit by hand.",
        "",
        "| run | model | threshold | seed | precision | recall | micro-F1 | runtime (s) |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    (RESULTS_DIR / "summary.md").write_text("\n".join(lines))
