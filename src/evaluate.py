"""Metrics and results logging shared by every model."""

import json
import re
import statistics
from pathlib import Path

import numpy as np
from sklearn.metrics import precision_recall_fscore_support

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "results"
DEFAULT_SEED = 42

# Candidate decision thresholds for tuning: 0.01, 0.02, ..., 0.99.
THRESHOLD_GRID = np.round(np.arange(0.01, 1.0, 0.01), 2)


def micro_metrics(y_true, y_pred):
    """Micro-averaged precision, recall and F1 over all 217 label columns."""
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_true, y_pred, average="micro", zero_division=0
    )
    return {"precision": float(precision), "recall": float(recall), "micro_f1": float(f1)}


def tune_threshold(y_val, val_scores):
    """Pick the single threshold (shared by all labels) that maximises validation micro-F1.

    Ties go to the lowest threshold. Only ever call this with validation data.
    Returns (threshold, validation micro-F1).
    """
    best_threshold, best_f1 = None, -1.0
    for threshold in THRESHOLD_GRID:
        f1 = micro_metrics(y_val, (val_scores >= threshold).astype(int))["micro_f1"]
        if f1 > best_f1:
            best_threshold, best_f1 = float(threshold), f1
    return best_threshold, best_f1


def tune_threshold_min_precision(y_val, val_scores, min_precision):
    """Pick the threshold with the best validation micro-F1 among those whose
    validation micro-precision is at least min_precision.

    Ties go to the lowest threshold. Only ever call this with validation data.
    Returns (threshold, validation micro-F1, validation precision), or
    (None, -1.0, None) if no threshold reaches min_precision.
    """
    best = (None, -1.0, None)
    for threshold in THRESHOLD_GRID:
        metrics = micro_metrics(y_val, (val_scores >= threshold).astype(int))
        if metrics["precision"] >= min_precision and metrics["micro_f1"] > best[1]:
            best = (float(threshold), metrics["micro_f1"], metrics["precision"])
    return best


def results_dir(dataset):
    """results/v1/ or results/v2/."""
    return RESULTS_DIR / dataset


def predictions_dir(dataset):
    return results_dir(dataset) / "predictions"


def seed_tag(seed):
    """Suffix for result names: empty for the default seed, "_seed<N>" otherwise."""
    return "" if seed == DEFAULT_SEED else f"_seed{seed}"


def save_result(run_name, result, test_predictions=None, test_scores=None):
    """Write one run to <results dir>/<run_name>.json and refresh that folder's summary.md.

    The folder depends on result["dataset"] (see results_dir). If given, the 0/1
    test predictions (and optionally the test scores) are saved to
    <results dir>/predictions/<run_name>.npz for the per-label analysis.
    """
    dataset = result["dataset"]
    out_dir = results_dir(dataset)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{run_name}.json"
    path.write_text(json.dumps(result, indent=2) + "\n")
    print(f"Wrote {path}")
    if test_predictions is not None:
        predictions_dir(dataset).mkdir(exist_ok=True)
        arrays = {"predictions": np.asarray(test_predictions, dtype=np.uint8)}
        if test_scores is not None:
            arrays["scores"] = np.asarray(test_scores, dtype=np.float16)
        np.savez_compressed(predictions_dir(dataset) / f"{run_name}.npz", **arrays)
    write_summary(dataset)


def write_summary(dataset="v2"):
    """Rebuild <results dir>/summary.md as one table of every run JSON in that folder."""
    out_dir = results_dir(dataset)
    rows = []
    for path in sorted(out_dir.glob("*.json")):
        r = json.loads(path.read_text())
        rows.append(
            f"| {path.stem} | {r['model']} | {r['threshold']} | {r['seed']} "
            f"| {r['precision']:.4f} | {r['recall']:.4f} | {r['micro_f1']:.4f} "
            f"| {r['runtime_seconds']:.0f} |"
        )
    # Runs that differ only by seed share a name once "_seed<N>" is removed.
    groups = {}
    for path in sorted(out_dir.glob("*.json")):
        groups.setdefault(re.sub(r"_seed\d+", "", path.stem), []).append(json.loads(path.read_text()))
    seed_rows = []
    for name, runs in groups.items():
        if len(runs) < 2:
            continue
        cells = []
        for metric in ("precision", "recall", "micro_f1"):
            values = [r[metric] for r in runs]
            cells.append(f"{statistics.mean(values):.4f} ± {statistics.stdev(values):.4f}")
        seed_rows.append(f"| {name} | {len(runs)} | " + " | ".join(cells) + " |")

    lines = [
        f"# Results summary ({dataset} labels)",
        "",
        "Test-set metrics, micro-averaged over all 217 labels. Generated by",
        "`src/evaluate.py` from the JSON files in this folder; do not edit by hand.",
        "",
        "| run | model | threshold | seed | precision | recall | micro-F1 | runtime (s) |",
        "|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Across seeds (mean ± sample standard deviation)",
        "",
        "| run | seeds | precision | recall | micro-F1 |",
        "|---|---|---|---|---|",
        *seed_rows,
        "",
    ]
    (out_dir / "summary.md").write_text("\n".join(lines))
